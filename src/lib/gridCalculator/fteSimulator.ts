/**
 * Default federal US holiday set — the working calendar for anesthesia groups
 * in v1. Floating holidays (MLK, Presidents Day, Memorial Day, Labor Day,
 * Thanksgiving) are computed for each year via `nthWeekdayOfMonth` /
 * `lastWeekdayOfMonth`. Christmas Eve is included so it triggers the holiday
 * post-call uplift even though it's not strictly federal.
 *
 * Configurable: pass `calendar.holidays = [...]` in `SimulatorInput` to
 * override; pass `[]` to disable holiday flagging entirely.
 */
export const DEFAULT_US_HOLIDAYS: HolidaySpec[] = [
  { name: 'New Year', date: '01-01' },
  { name: 'MLK Day', date: (y) => nthWeekdayOfMonth(y, 1, 1, 3) }, // 3rd Monday January
  { name: 'Presidents Day', date: (y) => nthWeekdayOfMonth(y, 2, 1, 3) }, // 3rd Monday February
  { name: 'Memorial Day', date: (y) => lastWeekdayOfMonth(y, 5, 1) }, // last Monday May
  { name: 'Independence Day', date: '07-04' },
  { name: 'Labor Day', date: (y) => nthWeekdayOfMonth(y, 9, 1, 1) }, // 1st Monday September
  { name: 'Thanksgiving', date: (y) => nthWeekdayOfMonth(y, 11, 4, 4) }, // 4th Thursday November
  { name: 'Day After Thanksgiving', date: (y) => nthWeekdayOfMonth(y, 11, 5, 4) }, // 4th Friday November
  { name: 'Christmas Eve', date: '12-24' },
  { name: 'Christmas', date: '12-25' },
];

/**
 * Generate a 365 (or 366) day calendar with weekday / weekend / holiday flags.
 *
 * Year handling: leap years emit 366 entries. Sites consuming the calendar
 * should iterate `days.length` rather than hard-coding 365.
 */
export function generateAnnualCalendar(options: CalendarOptions = {}): CalendarDay[] {
  const year = options.year ?? DEFAULT_CALENDAR_YEAR;
  const holidays = options.holidays ?? DEFAULT_US_HOLIDAYS;

  // Resolve each holiday to an ISO date for fast lookup.
  const holidayByIso = new Map<string, string>();
  for (const h of holidays) {
    const iso = resolveHolidayIso(h, year);
    if (iso !== null) holidayByIso.set(iso, h.name);
  }

  const days: CalendarDay[] = [];
  const start = new Date(Date.UTC(year, 0, 1));
  const end = new Date(Date.UTC(year + 1, 0, 1));
  let cursor = new Date(start);
  let dayIndex = 0;
  while (cursor < end) {
    const iso = isoDate(cursor);
    const dayOfWeek = cursor.getUTCDay();
    let type: CalendarDayType = 'weekday';
    if (dayOfWeek === 0 || dayOfWeek === 6) type = 'weekend';
    const holidayName = holidayByIso.get(iso);
    if (holidayName) type = 'holiday';

    days.push({
      date: iso,
      dayIndex,
      type,
      holidayName,
      dayOfWeek,
    });
    dayIndex += 1;
    cursor = new Date(cursor.getTime() + 86_400_000);
  }
  return days;
}

function isoDate(d: Date): string {
  const y = d.getUTCFullYear();
  const m = String(d.getUTCMonth() + 1).padStart(2, '0');
  const dd = String(d.getUTCDate()).padStart(2, '0');
  return `${y}-${m}-${dd}`;
}

function resolveHolidayIso(h: HolidaySpec, year: number): string | null {
  if (typeof h.date === 'string') {
    // MM-DD form.
    const [mm, dd] = h.date.split('-').map((s) => parseInt(s, 10));
    if (!Number.isFinite(mm) || !Number.isFinite(dd)) return null;
    return `${year}-${String(mm).padStart(2, '0')}-${String(dd).padStart(2, '0')}`;
  }
  const d = h.date(year);
  return isoDate(new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate())));
}

/**
 * Nth occurrence of `weekday` (0=Sun..6=Sat) in `month` (1-12) for `year`.
 * Returns a UTC midnight Date.
 */
export function nthWeekdayOfMonth(
  year: number,
  month: number,
  weekday: number,
  n: number,
): Date {
  // Walk from day 1 to find the first matching weekday; jump by 7 (n-1) times.
  const first = new Date(Date.UTC(year, month - 1, 1));
  const firstDow = first.getUTCDay();
  const offset = (weekday - firstDow + 7) % 7;
  const day = 1 + offset + (n - 1) * 7;
  return new Date(Date.UTC(year, month - 1, day));
}

/**
 * Last occurrence of `weekday` (0=Sun..6=Sat) in `month` for `year`. UTC.
 */
export function lastWeekdayOfMonth(year: number, month: number, weekday: number): Date {
  // Start at day 0 of next month, then walk back to the matching weekday.
  const lastDayOfMonth = new Date(Date.UTC(year, month, 0));
  const dow = lastDayOfMonth.getUTCDay();
  const offset = (dow - weekday + 7) % 7;
  return new Date(Date.UTC(year, month - 1, lastDayOfMonth.getUTCDate() - offset));
}

// ---------------------------------------------------------------------------
// Seeded RNG — xoshiro128**.
// ---------------------------------------------------------------------------
//
// Why xoshiro128**: small state (4 × uint32), fast in pure JS, well-studied,
// passes BigCrush. We seed via SplitMix32 from a single uint32 seed so test
// inputs can be a plain integer. Production seeding draws from crypto.
//
// All randomness inside the Monte Carlo loop flows through this RNG so two
// runs with the same seed produce byte-identical results.

export interface Rng {
  next(): number; // float in [0, 1)
  nextUint32(): number;
  nextInt(maxExclusive: number): number;
  /** Sample from Poisson(lambda) via Knuth's algorithm. */
  poisson(lambda: number): number;
  /**
   * Resolved uint32 seed actually used to initialize state. When the caller
   * passes a number, `seed === (caller >>> 0)`. When the caller passes
   * undefined, this exposes the crypto-drawn value so the simulator can
   * persist a reproducible seed (bug fix #4 from 2026-06-17 code review).
   */
  readonly seed: number;
}

/**
 * Build a seeded RNG. `seed` is a uint32; if undefined, we pull 4 bytes from
 * crypto.getRandomValues. Tests always pass an explicit seed.
 *
 * The returned `Rng` exposes the resolved `seed` on the object so callers
 * that didn't pass a seed can capture the crypto-drawn value for repro.
 */
export function createRng(seed?: number): Rng {
  const initialSeed = seed === undefined ? cryptoSeed() : seed >>> 0;
  // SplitMix32 to expand the single uint32 to a 4×uint32 xoshiro state.
  let sm = initialSeed >>> 0;
  const splitmix32 = (): number => {
    sm = (sm + 0x9e3779b9) >>> 0;
    let z = sm;
    z = Math.imul(z ^ (z >>> 16), 0x85ebca6b) >>> 0;
    z = Math.imul(z ^ (z >>> 13), 0xc2b2ae35) >>> 0;
    return (z ^ (z >>> 16)) >>> 0;
  };
  let s0 = splitmix32();
  let s1 = splitmix32();
  let s2 = splitmix32();
  let s3 = splitmix32();
  // Avoid all-zero state (xoshiro requirement).
  if ((s0 | s1 | s2 | s3) === 0) {
    s0 = 1;
  }

  const rotl = (x: number, k: number): number => ((x << k) | (x >>> (32 - k))) >>> 0;

  const nextUint32 = (): number => {
    const result = (Math.imul(rotl(Math.imul(s1, 5) >>> 0, 7), 9)) >>> 0;
    const t = (s1 << 9) >>> 0;
    s2 = (s2 ^ s0) >>> 0;
    s3 = (s3 ^ s1) >>> 0;
    s1 = (s1 ^ s2) >>> 0;
    s0 = (s0 ^ s3) >>> 0;
    s2 = (s2 ^ t) >>> 0;
    s3 = rotl(s3, 11);
    return result;
  };

  const next = (): number => {
    // 53-bit precision via two uint32s — standard pattern.
    const hi = nextUint32() >>> 5; // 27 bits
    const lo = nextUint32() >>> 6; // 26 bits
    return (hi * 67_108_864 + lo) / 9_007_199_254_740_992;
  };

  const nextInt = (maxExclusive: number): number => {
    if (maxExclusive <= 0) return 0;
    return Math.floor(next() * maxExclusive);
  };

  const poisson = (lambda: number): number => {
    // Knuth's algorithm. Fine for the small lambdas we expect (≤10).
    if (lambda <= 0) return 0;
    const L = Math.exp(-lambda);
    let k = 0;
    let p = 1;
    // Safety bound — avoid infinite loops if a bad lambda slips through.
    const HARD_CAP = 1000;
    while (p > L && k < HARD_CAP) {
      k += 1;
      p *= next();
    }
    return k - 1;
  };

  return { next, nextUint32, nextInt, poisson, seed: initialSeed };
}

function cryptoSeed(): number {
  // crypto.getRandomValues is available in Node ≥18 (`globalThis.crypto`).
  const g: { crypto?: { getRandomValues?: (a: Uint32Array) => Uint32Array } } =
    globalThis as unknown as {
      crypto?: { getRandomValues?: (a: Uint32Array) => Uint32Array };
    };
  if (g.crypto && typeof g.crypto.getRandomValues === 'function') {
    const arr = new Uint32Array(1);
    g.crypto.getRandomValues(arr);
    return arr[0] >>> 0;
  }
  // Last-resort fallback — should never hit in modern Node/Next environments.
  return (Date.now() ^ Math.floor(Math.random() * 0xffffffff)) >>> 0;
}

// ---------------------------------------------------------------------------
// Violation classification — distinguish "I can't staff this room" from
// "informational audit trail" (PRD §17 risk: solver round-trips audit-only
// flags that aren't shortages). Without this distinction, worst-case growth
// loops forever because the audit messages never disappear.
// ---------------------------------------------------------------------------

/** Substrings that mark a violation as a real staffing shortage. */
const SHORTAGE_VIOLATION_MARKERS = [
  'no Anesthesiologist available',
  'no CRNA available',
] as const;

/**
 * Return true if any violation in the list is a real shortage (not audit-only).
 * Audit-only patterns (round-tripped global rules, site-id fallbacks, no-rule
 * defaulting) are skipped because they don't get resolved by adding providers.
 */
function hasShortageViolation(violations: readonly string[]): boolean {
  return violations.some((v) =>
    SHORTAGE_VIOLATION_MARKERS.some((marker) => v.includes(marker)),
  );
}

// ---------------------------------------------------------------------------
// Worst-case deterministic path
// ---------------------------------------------------------------------------

/**
 * Find the minimum (anesthesiologist, CRNA) headcount that solves every
 * weekday cleanly under PRD §10 worst-case rules.
 *
 * Strategy:
 *   1. Generate a synthetic roster from the configured headcount.
 *   2. Apply worst-case hold-outs (maternity hold-out, forced PTOs, post-call
 *      vacancy, same-day call-out rates) per weekday.
 *   3. Solve. If any day has solver violations → grow the roster by 1 and try
 *      again. Cap growth at `RECOMMENDATION_MAX`.
 *
 * Determinism: this path is independent of any RNG. The "15% / 8% call-out"
 * is applied deterministically (every 7th CRNA, every 13th MD, rotating) so
 * the same inputs always produce the same answer. Same for the post-call
 * rotation.
 */
export function runWorstCase(input: SimulatorInput): WorstCaseResult {
  const calendar = generateAnnualCalendar(input.calendar);
  const weekdays = calendar.filter((d) => d.type === 'weekday');
  const notes: string[] = [];

  // Roster baseline counts: start from caller's roster size, then grow.
  const baselineMDs = input.roster.filter((r) => r.role === 'anesthesiologist').length;
  const baselineCRNAs = input.roster.filter((r) => r.role === 'crna').length;

  // Minimum starting headcount: at least 1 MD and 1 CRNA so the grow loop
  // can find an actual minimum even when the caller passes an empty roster.
  let mdCount = Math.max(1, baselineMDs);
  let crnaCount = Math.max(1, baselineCRNAs);

  // Cap iterations defensively.
  let unsolvable = 0;
  const MAX_LOOPS = RECOMMENDATION_MAX * 4;
  let loops = 0;

  while (loops < MAX_LOOPS) {
    loops += 1;
    if (mdCount > RECOMMENDATION_MAX || crnaCount > RECOMMENDATION_MAX) {
      notes.push(
        `Worst-case roster grew to >${RECOMMENDATION_MAX} — hard-capped per escalation rule.`,
      );
      mdCount = Math.min(mdCount, RECOMMENDATION_MAX);
      crnaCount = Math.min(crnaCount, RECOMMENDATION_MAX);
      break;
    }

    const synthetic = buildSyntheticRoster(mdCount, crnaCount);

    // Apply the maternity hold-out: remove one CRNA (typically the largest
    // cohort) for the entire year. PRD §10 says "one provider" — we pick
    // CRNA because it's the more common maternity-eligible cohort, and the
    // worst case is precisely "we lose a CRNA, not an MD" most of the year.
    const maternityHeldOut: RosterProvider | null =
      synthetic.find((r) => r.role === 'crna') ?? null;

    unsolvable = 0;
    let mdShort = false;
    let crnaShort = false;

    for (const day of weekdays) {
      const dayRoster = applyWorstCaseHoldouts(
        synthetic,
        day,
        maternityHeldOut?.id ?? null,
      );
      const grid = solve({
        config: input.config,
        sites: input.sites,
        rules: input.rules,
        roster: dayRoster,
        distanceMatrix: input.distanceMatrix,
      });
      if (hasShortageViolation(grid.violations)) {
        unsolvable += 1;
        // Classify the shortage so we know which role to grow. We grow both
        // if the violations span both roles.
        for (const v of grid.violations) {
          if (v.includes('no CRNA available')) crnaShort = true;
          if (v.includes('no Anesthesiologist available')) mdShort = true;
        }
      }
    }

    if (unsolvable === 0) {
      break; // success
    }

    // Grow whichever role surfaced as the bottleneck. If neither classified
    // (rare — the violation text changed?), grow CRNAs first since they're
    // the larger pool typically.
    if (mdShort) mdCount += 1;
    if (crnaShort) crnaCount += 1;
    if (!mdShort && !crnaShort) crnaCount += 1;
  }

  // Subtract the maternity hold-out so the *output* is the recommended
  // recurring headcount (not the on-the-books-during-leave count).
  // Per PRD §10 wording, the recommended FTE IS the worst-case minimum that
  // still works — the hold-out is the structural buffer the roster needs.
  // We return the roster size that produced success, not the per-day count.
  //
  // Bug fix #2 (2026-06-17 code review): re-run one final solve pass with the
  // ACCEPTED roster so `unsolvableDays` describes the roster we're reporting,
  // not just the last (potentially mid-growth) iteration. If the grow loop hit
  // the RECOMMENDATION_MAX cap, this surfaces the residual shortage on the
  // capped headcount, which is what the caller (rationale, audit row) needs.
  const finalMDCount = Math.min(mdCount, RECOMMENDATION_MAX);
  const finalCRNACount = Math.min(crnaCount, RECOMMENDATION_MAX);
  const finalRoster = buildSyntheticRoster(finalMDCount, finalCRNACount);
  const finalMaternityHeldOut: RosterProvider | null =
    finalRoster.find((r) => r.role === 'crna') ?? null;
  let finalUnsolvable = 0;
  for (const day of weekdays) {
    const dayRoster = applyWorstCaseHoldouts(
      finalRoster,
      day,
      finalMaternityHeldOut?.id ?? null,
    );
    const grid = solve({
      config: input.config,
      sites: input.sites,
      rules: input.rules,
      roster: dayRoster,
      distanceMatrix: input.distanceMatrix,
    });
    if (hasShortageViolation(grid.violations)) {
      finalUnsolvable += 1;
    }
  }

  return {
    anesthesiologists: clampRecommendation(finalMDCount),
    crnas: clampRecommendation(finalCRNACount),
    weekdaysEvaluated: weekdays.length,
    unsolvableDays: finalUnsolvable,
    notes,
  };
}

/**
 * Build a synthetic roster of `mdCount` Anesthesiologists and `crnaCount`
 * CRNAs at FTE 1.0 each. IDs are deterministic so subsequent simulator runs
 * with the same headcount produce the same hold-out picks.
 */
function buildSyntheticRoster(mdCount: number, crnaCount: number): RosterProvider[] {
  const roster: RosterProvider[] = [];
  for (let i = 0; i < mdCount; i++) {
    roster.push({ id: `wc-md-${String(i + 1).padStart(3, '0')}`, role: 'anesthesiologist', fte: 1.0 });
  }
  for (let i = 0; i < crnaCount; i++) {
    roster.push({ id: `wc-crna-${String(i + 1).padStart(3, '0')}`, role: 'crna', fte: 1.0 });
  }
  return roster;
}

/**
 * Apply PRD §10 worst-case hold-outs to a single weekday's roster.
 *
 *   - The maternity-held-out provider is unavailable every day.
 *   - 15% of remaining CRNAs (deterministically rotated) called out.
 *   - 8% of remaining MDs (deterministically rotated) called out.
 *   - 2 forced PTOs (1 MD + 1 CRNA) — also rotated across the year.
 *   - 1 post-call vacancy (an MD if available, otherwise a CRNA) per weekday.
 *
 * Determinism: we use the day index to rotate which providers are absent so
 * results are reproducible without any RNG. The rotation also spreads burden
 * across the synthetic roster — no single provider is held out for the whole
 * year unless we'd need to roll around the entire pool first.
 */
function applyWorstCaseHoldouts(
  roster: RosterProvider[],
  day: CalendarDay,
  maternityHeldOutId: string | null,
): RosterProvider[] {
  const mds = roster.filter((r) => r.role === 'anesthesiologist' && r.id !== maternityHeldOutId);
  const crnas = roster.filter((r) => r.role === 'crna' && r.id !== maternityHeldOutId);

  // 15% CRNA call-out, 8% MD call-out. Use ceil so even tiny rosters lose at
  // least one provider once the threshold is crossed.
  const crnaCalloutCount = Math.ceil(crnas.length * WORST_CASE_CRNA_CALLOUT_RATE);
  const mdCalloutCount = Math.ceil(mds.length * WORST_CASE_MD_CALLOUT_RATE);

  const calledOut = new Set<string>();

  // Rotate the call-out window across the year so a different cohort is
  // affected each day. day.dayIndex acts as the rotation offset.
  for (let i = 0; i < crnaCalloutCount; i++) {
    if (crnas.length === 0) break;
    const idx = (day.dayIndex + i * 7) % crnas.length;
    calledOut.add(crnas[idx].id);
  }
  for (let i = 0; i < mdCalloutCount; i++) {
    if (mds.length === 0) break;
    const idx = (day.dayIndex + i * 13) % mds.length;
    calledOut.add(mds[idx].id);
  }

  // Forced PTOs (1 MD + 1 CRNA), rotated so they don't always collide.
  if (mds.length > 0) {
    for (let i = 0; i < WORST_CASE_FORCED_PTO_MD; i++) {
      const idx = (day.dayIndex * 3 + i) % mds.length;
      calledOut.add(mds[idx].id);
    }
  }
  if (crnas.length > 0) {
    for (let i = 0; i < WORST_CASE_FORCED_PTO_CRNA; i++) {
      const idx = (day.dayIndex * 5 + i) % crnas.length;
      calledOut.add(crnas[idx].id);
    }
  }

  // Post-call vacancy — prefer MD if available; CRNAs already lose enough.
  if (WORST_CASE_FORCED_POST_CALL_PER_WEEKDAY > 0 && mds.length > 0) {
    const idx = (day.dayIndex + 1) % mds.length;
    calledOut.add(mds[idx].id);
  }

  if (maternityHeldOutId) calledOut.add(maternityHeldOutId);

  return roster.filter((r) => !calledOut.has(r.id));
}

