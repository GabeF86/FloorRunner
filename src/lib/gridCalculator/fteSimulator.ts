/**
 * Run both simulations, assemble the recommendation, generate a rationale.
 * This is the production entry point — the nightly cron and the on-demand
 * UI button both call it.
 *
 * Float-health auto-bump (PRD §12): if `floatTroubleFraction` exceeds the
 * threshold, the recommendation gets +1 CRNA and we re-run Monte Carlo (the
 * extra CRNA shows up as a float candidate). We cap iterations defensively.
 */
export async function simulate(input: SimulatorInput): Promise<FTERunResult> {
  const trialsCount = input.trialsCount ?? DEFAULT_TRIALS_COUNT;

  // Bug fix #4 (2026-06-17 code review): resolve the RNG seed ONCE up front
  // so we (a) can persist a reproducible value when input.seed is undefined
  // and (b) keep all Monte Carlo iterations on the same seed across the
  // float-bump loop. Without this, each runMonteCarlo() call with an
  // undefined input.seed would draw a fresh crypto seed, and we'd report
  // NaN to grid_calculator_fte_runs.seed (un-reproducible).
  const resolvedSeed = createRng(input.seed).seed;
  const seededInput: SimulatorInput = { ...input, seed: resolvedSeed };

  let worstCase = runWorstCase(seededInput);
  let monteCarlo = runMonteCarlo(seededInput, trialsCount);

  // PRD §12 — auto-bump 1 CRNA if float feasibility drops below tight on
  // more than 10% of simulated days. Repeat up to MAX_FLOAT_HEALTH_BUMPS.
  let augmentedInput = seededInput;
  let bumpCount = 0;
  while (
    monteCarlo.floatTroubleFraction > FLOAT_HEALTH_BUMP_THRESHOLD &&
    bumpCount < MAX_FLOAT_HEALTH_BUMPS
  ) {
    bumpCount += 1;
    augmentedInput = {
      ...augmentedInput,
      roster: [
        ...augmentedInput.roster,
        {
          id: `bump-crna-${bumpCount}`,
          role: 'crna',
          fte: 1.0,
        } satisfies RosterProvider,
      ],
    };
    monteCarlo = runMonteCarlo(augmentedInput, trialsCount);
    monteCarlo.floatBumpApplied = true;
    monteCarlo.floatBumpCount = bumpCount;
  }
  if (bumpCount > 0) {
    monteCarlo.floatBumpApplied = true;
    monteCarlo.floatBumpCount = bumpCount;
    // Bug fix #3 (2026-06-17 code review): re-run worstCase against the
    // bumped roster so both halves of `recommendFTE` see the same context.
    // Without this, the worstCase block describes the un-bumped roster while
    // the Monte Carlo block describes the bumped one — and the rationale /
    // audit row report inconsistent context.
    worstCase = runWorstCase(augmentedInput);
  }

  const { recommendation, callBurden, violations } = recommendFTE(
    worstCase,
    monteCarlo,
    augmentedInput,
  );

  const { rationale, fallback } = await generateRationale({
    recommendation,
    worstCase,
    monteCarlo,
    client: input.anthropicClient,
    model: input.rationaleModel ?? DEFAULT_RATIONALE_MODEL,
  });

  return {
    ...recommendation,
    rationale,
    worstCase,
    monteCarlo,
    callBurden,
    rationaleFallback: fallback,
    violations,
    seed: resolvedSeed,
  };
}

// ---------------------------------------------------------------------------
// Persistence helper — exported so the API route / cron can wire it in.
// The simulator never imports a Supabase client; callers inject a thin
// `persist` shape so the module stays pure-by-default.
// ---------------------------------------------------------------------------

export interface PersistableFTERun {
  configId: string;
  ranAt: string;
  worstCase: WorstCaseResult;
  monteCarlo: MonteCarloResult;
  recommendation: FTERecommendation;
  rationale: string;
}

export interface SimplePersister {
  insert(row: PersistableFTERun): Promise<void>;
}

/**
 * Convert an `FTERunResult` into the row shape expected by patch 16's
 * `scheduling.grid_calculator_fte_runs` table. Callers pass a `persister`
 * (a thin Supabase wrapper) to actually write the row.
 */
export async function persistFTERun(
  configId: string,
  run: FTERunResult,
  persister: SimplePersister,
): Promise<void> {
  const recommendation: FTERecommendation = {
    anesthesiologist: run.anesthesiologist,
    crna: run.crna,
    backupCall: run.backupCall,
    rationale: run.rationale,
  };
  await persister.insert({
    configId,
    ranAt: new Date().toISOString(),
    worstCase: run.worstCase,
    monteCarlo: run.monteCarlo,
    recommendation,
    rationale: run.rationale,
  });
}

