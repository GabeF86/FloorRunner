// Worst-case + Monte Carlo FTE demand simulator.
// Owned by agent A7 (FTE Simulator).
//
// PURPOSE
// -------
// Given a config + roster + sites + rules, run two complementary simulations
// to recommend an FTE headcount that defensibly staffs the contract:
//
//   1. Worst-case deterministic (PRD §10):
//        - Hold out one provider for maternity (12 weeks).
//        - Force a 15% same-day call-out among CRNAs, 8% among Anesthesiologists.
//        - Force 2 simultaneous PTOs (one Anesthesiologist + one CRNA).
//        - Force 1 post-call vacancy each weekday.
//        - The recommendation is the smallest roster that produces a valid grid
//          (zero solver violations) on every weekday in the calendar year.
//
//   2. Monte Carlo over 365 simulated days × N trials (default 1000):
//        - PTO weeks per provider drawn from `pto_weeks` profile field.
//        - Sick/personal call-outs via Poisson with `sick_days_per_year` lambda.
//        - FMLA / maternity sampled from per-cohort probability flags.
//        - Post-call vacancies derived from a primary-call rotation.
//        - Weekends + federal holidays generated by the calendar utility.
//        - Reports p50 and p95 FTE for each role.
//
// The final `FTERecommendation` per role is `max(worstCase, p95)`. The binding
// constraint is labeled so the UI can explain "why this number".
//
// Universality contract: zero FloorRunner-specific imports. Everything is
// pure functions + a deterministic RNG seeded by the caller. Production
// callers pass `seed=undefined` so the wrapper picks a crypto-secure seed;
// tests pass an explicit seed for reproducibility.
//
// PERSISTENCE
// -----------
// `persistFTERun` writes the result to `scheduling.grid_calculator_fte_runs`
// when a Supabase client is provided. The simulator never imports a Supabase
// client directly; the caller (UI / cron) injects one to keep the module
// pure-by-default.
//
// PRD: docs/PRD-Grid-Calculator.md §5, §10, §11, §12, §13, §14 (A7), §16.

