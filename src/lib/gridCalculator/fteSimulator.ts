/**
 * Combine worst-case + Monte Carlo into a final `FTERecommendation`.
 *
 *   - `worstCase` and `p95` per role are compared; the larger wins, and
 *     `binding` records which constraint drove the number.
 *   - Backup call distribution is assembled via A8's `distributeCall` from
 *     the provided `callRoster` (or a synthesized roster if missing).
 *   - Anything outside [0, 200] is hard-capped and a violation is added.
 *
 * Note: this function is pure — no rationale is generated here. The rationale
 * is produced by the async `simulate()` wrapper.
 */
export function recommendFTE(
  worstCase: WorstCaseResult,
  monteCarlo: MonteCarloResult,
  input: SimulatorInput,
): {
  recommendation: Omit<FTERecommendation, 'rationale'>;
  callBurden: {
    perProvider: ProviderCallBurden[];
    gini: number;
    violations: string[];
  };
  violations: string[];
} {
  const violations: string[] = [];

  const mdBlock = buildBlock(
    worstCase.anesthesiologists,
    monteCarlo.anesthesiologists,
    violations,
    'Anesthesiologist',
  );
  const crnaBlock = buildBlock(
    worstCase.crnas,
    monteCarlo.crnas,
    violations,
    'CRNA',
  );

  // Backup-call distribution via A8.
  const callRoster = input.callRoster ?? synthesizeCallRoster(input);
  const annualBackupSlots = Math.max(1, Math.round(ANNUAL_PRIMARY_CALL_SLOTS * 0.5));
  const callOutput = distributeCall({
    roster: callRoster,
    annualPrimarySlots: ANNUAL_PRIMARY_CALL_SLOTS,
    annualBackupSlots,
    posture: input.config.backupCallPosture,
    providerLeaveProfiles: input.providerLeaveProfiles ?? {},
  });

  for (const v of callOutput.violations) violations.push(`callBurden: ${v}`);

  // The "backup call FTE" magnitude: PRD §11 frames it as a fractional share
  // summing to 1.0 of the total backup-call demand. Express the headline
  // number as the sum of shares (i.e. ~1.0 when properly allocated). The UI
  // multiplies by annualBackupSlots when needed.
  const totalBackupFte = callOutput.perProvider.reduce(
    (acc, p) => acc + p.backupCallFteShare,
    0,
  );

  const distribution = callOutput.perProvider
    .filter((p) => p.backupCallFteShare > 0)
    .map((p) => ({
      providerId: p.providerId,
      fteShare: p.backupCallFteShare,
    }));

  const recommendation: Omit<FTERecommendation, 'rationale'> = {
    anesthesiologist: mdBlock,
    crna: crnaBlock,
    backupCall: {
      fte: roundShare(totalBackupFte),
      distribution,
    },
  };

  return {
    recommendation,
    callBurden: {
      perProvider: callOutput.perProvider,
      gini: callOutput.gini,
      violations: callOutput.violations,
    },
    violations,
  };
}

function buildBlock(
  worstCase: number,
  mc: MonteCarloRoleStat,
  violations: string[],
  label: string,
): FTEBlock {
  const wcClamped = clampRecommendation(worstCase);
  const p50Clamped = clampRecommendation(mc.p50);
  const p95Clamped = clampRecommendation(mc.p95);

  if (
    worstCase !== wcClamped ||
    mc.p50 !== p50Clamped ||
    mc.p95 !== p95Clamped
  ) {
    violations.push(
      `${label} recommendation hit [0, ${RECOMMENDATION_MAX}] hard cap — likely a sim bug.`,
    );
  }

  const binding: 'worst_case' | 'monte_carlo' =
    wcClamped >= p95Clamped ? 'worst_case' : 'monte_carlo';

  return {
    worstCase: wcClamped,
    p50: roundShare(p50Clamped),
    p95: roundShare(p95Clamped),
    binding,
  };
}

function clampRecommendation(n: number): number {
  if (!Number.isFinite(n)) return 0;
  if (n < RECOMMENDATION_MIN) return RECOMMENDATION_MIN;
  if (n > RECOMMENDATION_MAX) return RECOMMENDATION_MAX;
  return n;
}

function roundShare(n: number): number {
  return Math.round(n * 100) / 100;
}

function synthesizeCallRoster(input: SimulatorInput): CallRosterEntry[] {
  // Synthesize from the supplied roster: every provider is treated as both
  // call_taker and backup_call_eligible at their FTE. Real callers should
  // pass an explicit callRoster.
  return input.roster.map((r) => ({
    id: r.id,
    fte: r.fte,
    call_taker: true,
    backup_call_eligible: true,
  }));
}

