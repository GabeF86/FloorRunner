/** PRD §14 (A7): pin rationale to claude-sonnet-4-6 for speed. */
export const DEFAULT_RATIONALE_MODEL = 'claude-sonnet-4-6';

/**
 * System prompt for the rationale generator. Kept short — the rationale is
 * 1–3 sentences of plain English aimed at hospital administrators.
 *
 * Cached via `cache_control: ephemeral` so repeat runs on the same config hit
 * the cache (the user prompt is the variable bit).
 */
export const RATIONALE_SYSTEM_PROMPT =
  `You are explaining a hospital anesthesia staffing recommendation to a hospital administrator. ` +
  `Write 2-3 plain-English sentences explaining the recommended Anesthesiologist and CRNA FTE counts. ` +
  `Focus on what made the recommendation binding (worst-case vs Monte Carlo p95) and why. ` +
  `Do not hedge; do not use bullet points; do not repeat the numbers more than necessary.`;

/**
 * Templated fallback rationale used when `ANTHROPIC_API_KEY` is unset or the
 * client throws. Deterministic and information-dense; satisfies the PRD
 * requirement that *some* rationale always ship.
 */
export function buildTemplatedRationale(
  recommendation: Omit<FTERecommendation, 'rationale'>,
  worstCase: WorstCaseResult,
  monteCarlo: MonteCarloResult,
): string {
  const md = recommendation.anesthesiologist;
  const crna = recommendation.crna;
  const mdBindingPhrase =
    md.binding === 'worst_case'
      ? `worst-case (1 maternity hold-out + 15% CRNA / 8% Anesthesiologist call-out + 2 PTOs + post-call vacancy)`
      : `Monte Carlo p95 over ${monteCarlo.trialsCount} trials`;
  const crnaBindingPhrase =
    crna.binding === 'worst_case'
      ? `worst-case scenarios`
      : `Monte Carlo p95 over ${monteCarlo.trialsCount} trials`;
  const floatNote = monteCarlo.floatBumpApplied
    ? ` Float-health auto-bump fired ${monteCarlo.floatBumpCount} time(s) because break feasibility dropped below \`tight\` on more than ${Math.round(FLOAT_HEALTH_BUMP_THRESHOLD * 100)}% of simulated days, so an extra float CRNA is baked in.`
    : '';
  return (
    `Recommended ${md.worstCase} Anesthesiologists and ${crna.worstCase} CRNAs ` +
    `(binding constraint: Anesthesiologist=${mdBindingPhrase}; CRNA=${crnaBindingPhrase}). ` +
    `Worst-case roster solved every weekday in ${worstCase.weekdaysEvaluated} simulated weekdays; ` +
    `Monte Carlo p50/p95 were ${md.p50}/${md.p95} for Anesthesiologists and ${crna.p50}/${crna.p95} for CRNAs.` +
    floatNote
  );
}

interface RationaleArgs {
  recommendation: Omit<FTERecommendation, 'rationale'>;
  worstCase: WorstCaseResult;
  monteCarlo: MonteCarloResult;
  client: RationaleClient | null | undefined;
  model: string;
}

interface RationaleOutcome {
  rationale: string;
  fallback: boolean;
}

async function generateRationale(args: RationaleArgs): Promise<RationaleOutcome> {
  const templated = buildTemplatedRationale(
    args.recommendation,
    args.worstCase,
    args.monteCarlo,
  );

  // Explicit null: caller forced fallback (tests do this).
  if (args.client === null) {
    return { rationale: templated, fallback: true };
  }

  // Undefined: build a real client if the API key is present, else fall back.
  let client: RationaleClient | null;
  if (args.client === undefined) {
    client = await tryBuildAnthropicClient();
  } else {
    client = args.client;
  }
  if (client === null) {
    return { rationale: templated, fallback: true };
  }

  const liveClient: RationaleClient = client;
  try {
    const userMessage = buildRationaleUserMessage(
      args.recommendation,
      args.worstCase,
      args.monteCarlo,
    );
    const response = await liveClient.messages.create({
      model: args.model,
      max_tokens: 512,
      system: [
        {
          type: 'text',
          text: RATIONALE_SYSTEM_PROMPT,
          cache_control: { type: 'ephemeral' },
        },
      ],
      messages: [{ role: 'user', content: userMessage }],
    });
    const text = response.content.find(
      (b): b is { type: string; text: string } =>
        b.type === 'text' && typeof b.text === 'string',
    )?.text?.trim();
    if (!text) {
      return { rationale: templated, fallback: true };
    }
    return { rationale: text, fallback: false };
  } catch {
    // Network / SDK / API error → fall back silently. The UI surfaces the
    // recommendation either way; we don't want a rationale failure to block.
    return { rationale: templated, fallback: true };
  }
}

async function tryBuildAnthropicClient(): Promise<RationaleClient | null> {
  // Lazy-load the SDK to keep this module importable in environments where
  // the SDK isn't installed (e.g. unit tests with no node_modules).
  // We import dynamically inside a try block so missing-package is a soft
  // failure, not a hard crash.
  //
  // Bug fix #6 (2026-06-17 code review): switched from `require` to dynamic
  // `import()` so bundlers (Next.js / esbuild) can tree-shake the SDK out of
  // the client bundle and so the SDK shape is type-checked.
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey || apiKey.trim().length === 0) return null;
  try {
    const sdk = await import('@anthropic-ai/sdk');
    const Ctor =
      (sdk as { default?: unknown }).default ??
      (sdk as { Anthropic?: unknown }).Anthropic ??
      sdk;
    const real = new (Ctor as new (opts: { apiKey: string }) => unknown)({
      apiKey,
    });
    return real as RationaleClient;
  } catch {
    return null;
  }
}

function buildRationaleUserMessage(
  recommendation: Omit<FTERecommendation, 'rationale'>,
  worstCase: WorstCaseResult,
  monteCarlo: MonteCarloResult,
): string {
  const payload = {
    recommendation: {
      anesthesiologist: recommendation.anesthesiologist,
      crna: recommendation.crna,
      backupCallFte: recommendation.backupCall.fte,
    },
    worstCase: {
      anesthesiologists: worstCase.anesthesiologists,
      crnas: worstCase.crnas,
      weekdaysEvaluated: worstCase.weekdaysEvaluated,
    },
    monteCarlo: {
      trialsCount: monteCarlo.trialsCount,
      floatTroubleFraction: monteCarlo.floatTroubleFraction,
      floatBumpApplied: monteCarlo.floatBumpApplied,
    },
  };
  return `Summarize this anesthesia FTE recommendation:\n${JSON.stringify(payload, null, 2)}`;
}

