interface TrialOutcome {
  /** Maximum MDs needed on any weekday in this trial. */
  peakMDs: number;
  /** Maximum CRNAs needed on any weekday in this trial. */
  peakCRNAs: number;
  /** Float-trouble fraction for the trial (used for PRD §12 auto-bump). */
  floatTroubleFraction: number;
}

/**
 * Run `trialsCount` independent simulated years. Each trial samples per-
 * provider leave from the configured profiles and tracks the peak weekday
 * roster requirement. Returns p50 / p95 / mean / stddev across trials.
 *
 * Note: roster sizing inside a trial uses a "grow as needed" pass — we never
 * try to enforce a specific roster size, we measure how many providers were
 * actively needed across the year. The recommendation is then the p95 of
 * those peaks.
 */
export function runMonteCarlo(
  input: SimulatorInput,
  trialsCount = DEFAULT_TRIALS_COUNT,
): MonteCarloResult {
  const calendar = generateAnnualCalendar(input.calendar);
  const weekdays = calendar.filter((d) => d.type === 'weekday');
  const rng = createRng(input.seed);

  const profiles = input.providerLeaveProfiles ?? {};

  // Per-trial peak headcount samples.
  const mdSamples: number[] = [];
  const crnaSamples: number[] = [];
  const floatTroubleSamples: number[] = [];

  // Baseline roster size. When the caller passes a roster, we honor it — the
  // simulator measures the PEAK headcount actually needed across the year.
  // When the roster is empty (e.g. greenfield contract), we synthesize a
  // headcount sized at room-count + 5 so the simulation has slack to absorb
  // leave draws and still report a meaningful peak.
  const baselineMDs = input.roster.filter((r) => r.role === 'anesthesiologist').length;
  const baselineCRNAs = input.roster.filter((r) => r.role === 'crna').length;

  const trialMdCount = baselineMDs > 0 ? baselineMDs : totalRoomCount(input.sites) + 5;
  const trialCrnaCount = baselineCRNAs > 0 ? baselineCRNAs : totalRoomCount(input.sites) + 5;

  for (let t = 0; t < trialsCount; t++) {
    const trial = runOneTrial({
      input,
      calendar,
      weekdays,
      rng,
      profiles,
      mdCount: trialMdCount,
      crnaCount: trialCrnaCount,
    });
    mdSamples.push(trial.peakMDs);
    crnaSamples.push(trial.peakCRNAs);
    floatTroubleSamples.push(trial.floatTroubleFraction);
  }

  return {
    trialsCount,
    anesthesiologists: summarizeStats(mdSamples),
    crnas: summarizeStats(crnaSamples),
    floatTroubleFraction: mean(floatTroubleSamples),
    floatBumpApplied: false,
    floatBumpCount: 0,
  };
}

function totalRoomCount(sites: GridSite[]): number {
  return sites.reduce((acc, s) => acc + s.rooms.length, 0);
}

function summarizeStats(samples: number[]): MonteCarloRoleStat {
  if (samples.length === 0) {
    return { p50: 0, p95: 0, mean: 0, stddev: 0 };
  }
  const sorted = [...samples].sort((a, b) => a - b);
  return {
    p50: clampRecommendation(percentile(sorted, 0.5)),
    p95: clampRecommendation(percentile(sorted, 0.95)),
    mean: clampRecommendation(mean(samples)),
    stddev: stddev(samples),
  };
}

function percentile(sortedAsc: number[], p: number): number {
  if (sortedAsc.length === 0) return 0;
  const rank = p * (sortedAsc.length - 1);
  const lo = Math.floor(rank);
  const hi = Math.ceil(rank);
  if (lo === hi) return sortedAsc[lo];
  const frac = rank - lo;
  return sortedAsc[lo] * (1 - frac) + sortedAsc[hi] * frac;
}

function mean(xs: number[]): number {
  if (xs.length === 0) return 0;
  return xs.reduce((a, b) => a + b, 0) / xs.length;
}

function stddev(xs: number[]): number {
  if (xs.length < 2) return 0;
  const m = mean(xs);
  const v = xs.reduce((a, b) => a + (b - m) ** 2, 0) / (xs.length - 1);
  return Math.sqrt(v);
}

interface TrialContext {
  input: SimulatorInput;
  calendar: CalendarDay[];
  weekdays: CalendarDay[];
  rng: Rng;
  profiles: Record<string, Partial<ProviderLeaveProfile>>;
  mdCount: number;
  crnaCount: number;
}

function runOneTrial(ctx: TrialContext): TrialOutcome {
  const { input, weekdays, rng, profiles, mdCount, crnaCount } = ctx;
  const roster = buildSyntheticRoster(mdCount, crnaCount);

  // Sample per-provider PTO weeks (jitter ±1 week around the configured
  // mean), sick days (Poisson), CME days, and FMLA event.
  // We then convert those to a set of "absent on day i" markers for each
  // provider — a uniform random subset of weekdays.
  const absentByDay = new Map<number, Set<string>>();
  for (const day of weekdays) absentByDay.set(day.dayIndex, new Set());

  for (const p of roster) {
    const profile = withProfileDefaults(profiles[p.id] ?? {});
    const ptoDays = Math.max(0, Math.round(profile.pto_weeks * WORK_DAYS_PER_PTO_WEEK + (rng.next() - 0.5) * 2));
    const sickDays = rng.poisson(profile.sick_days_per_year);
    const cmeDays = profile.cme_days_per_year;

    let fmlaDays = 0;
    if (profile.fmla_eligible && rng.next() < 0.04) {
      // 60 working days FMLA event when triggered — matches providerProfile default.
      fmlaDays = 60;
    }

    // Maternity: matches the worst-case treatment but stochastic here.
    let maternityDays = 0;
    if (profile.maternity_eligible && rng.next() < 0.05) {
      maternityDays = WORST_CASE_MATERNITY_WEEKS * WORK_DAYS_PER_PTO_WEEK;
    }

    const totalAbsentDays = Math.min(weekdays.length, ptoDays + sickDays + cmeDays + fmlaDays + maternityDays);
    // Distribute absences uniformly across weekdays. We sample WITHOUT
    // replacement so a single provider can't be "absent twice" on the same day.
    const absentDayIndices = sampleWithoutReplacement(weekdays.length, totalAbsentDays, rng);
    for (const wIdx of absentDayIndices) {
      const day = weekdays[wIdx];
      absentByDay.get(day.dayIndex)?.add(p.id);
    }
  }

  // For each weekday, drop absent providers and solve. Track peak roster
  // needed (assignments + floats consumed) and float trouble.
  let peakMDs = 0;
  let peakCRNAs = 0;
  let troubleDays = 0;

  for (const day of weekdays) {
    const absent = absentByDay.get(day.dayIndex) ?? new Set();
    const dayRoster = roster.filter((r) => !absent.has(r.id));

    const grid = solve({
      config: input.config,
      sites: input.sites,
      rules: input.rules,
      roster: dayRoster,
      distanceMatrix: input.distanceMatrix,
    });

    const used = countUsedProviders(grid);
    // Per-day shortage: count UNIQUE rooms that surfaced an "no X available"
    // violation so we don't double-count multi-line violation messages from a
    // single under-staffed room. Then add the shortage to the day's used
    // headcount and compare to the running peak. The previous implementation
    // used `+=` against the running peak, which permanently inflated it across
    // days (bug fix #1 from 2026-06-17 code review).
    const shortRoomsMDs = new Set<string>();
    const shortRoomsCRNAs = new Set<string>();
    for (const v of grid.violations) {
      const roomKey = extractRoomKey(v);
      if (v.includes('no Anesthesiologist available')) {
        shortRoomsMDs.add(roomKey);
      }
      if (v.includes('no CRNA available')) {
        shortRoomsCRNAs.add(roomKey);
      }
    }
    const dayMDs = used.mds + shortRoomsMDs.size;
    const dayCRNAs = used.crnas + shortRoomsCRNAs.size;
    if (dayMDs > peakMDs) peakMDs = dayMDs;
    if (dayCRNAs > peakCRNAs) peakCRNAs = dayCRNAs;

    // Float health for this day.
    const surplus = computeSurplus(dayRoster, grid);
    const withFloats = applyFloatStrategy(grid, {
      mode: input.config.floatStrategy,
      surplus,
      sites: input.sites,
      distanceMatrix: input.distanceMatrixForFloats,
    });
    const health = assessFloatHealth(withFloats, surplus);
    if (isBelowTight(health.level)) troubleDays += 1;
  }

  const floatTroubleFraction = weekdays.length === 0 ? 0 : troubleDays / weekdays.length;

  return { peakMDs, peakCRNAs, floatTroubleFraction };
}

/**
 * Extract the per-room key from a solver violation string so the trial loop
 * can count UNIQUE shortages per day. Solver violations are of the form
 * `Room <Site:Room>: no <Role> available...`; if the prefix doesn't match,
 * fall back to the full string so each unique message still counts once.
 */
function extractRoomKey(violation: string): string {
  const colonIdx = violation.indexOf(':');
  if (colonIdx < 0) return violation;
  return violation.slice(0, colonIdx);
}

function countUsedProviders(grid: SolvedGrid): { mds: number; crnas: number } {
  const mds = new Set<string>();
  const crnas = new Set<string>();
  for (const a of grid.assignments) {
    if (a.anesthesiologistId) mds.add(a.anesthesiologistId);
    for (const c of a.crnaIds) crnas.add(c);
  }
  for (const f of grid.floats) {
    if (f.role === 'anesthesiologist') mds.add(f.providerId);
    else crnas.add(f.providerId);
  }
  return { mds: mds.size, crnas: crnas.size };
}

function computeSurplus(roster: RosterProvider[], grid: SolvedGrid): FloatSurplusProvider[] {
  const used = new Set<string>();
  for (const a of grid.assignments) {
    if (a.anesthesiologistId) used.add(a.anesthesiologistId);
    for (const c of a.crnaIds) used.add(c);
  }
  for (const f of grid.floats) used.add(f.providerId);
  return roster
    .filter((r) => !used.has(r.id))
    .map((r) => ({ id: r.id, role: r.role }));
}

function isBelowTight(level: FloatHealthLevel): boolean {
  return level === 'warning' || level === 'critical';
}

/**
 * Sample `count` distinct indices in [0, n). Fisher-Yates partial shuffle on
 * a small array — fine for our scale (n ≤ ~260 weekdays, count ≤ n).
 *
 * Exported so tests can exercise the HARD_CAP fallback path; not part of the
 * public API contract (kept internal to the simulator module).
 */
export function sampleWithoutReplacement(n: number, count: number, rng: Rng): number[] {
  if (count <= 0 || n <= 0) return [];
  if (count >= n) return Array.from({ length: n }, (_, i) => i);
  // Build a sparse array for memory efficiency vs full Fisher-Yates.
  // For count ≪ n, repeated draws + Set check is cheaper than allocating n.
  if (count * 4 < n) {
    const out = new Set<number>();
    const HARD_CAP = count * 50;
    let attempts = 0;
    while (out.size < count && attempts < HARD_CAP) {
      out.add(rng.nextInt(n));
      attempts += 1;
    }
    // Bug fix #5 (2026-06-17 code review): if collisions exhausted the cap
    // before we reached `count`, fall through to the dense Fisher-Yates path
    // instead of returning a silently truncated set. The previous behavior
    // biased peak headcount downward when count approached n/4 and the
    // draw-and-check strategy stopped converging.
    if (out.size === count) {
      return [...out];
    }
  }
  const pool = Array.from({ length: n }, (_, i) => i);
  for (let i = 0; i < count; i++) {
    const j = i + rng.nextInt(n - i);
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, count);
}

